-- 20261125115100_step_owner_restarts.up.sql — how many times the daemon started the owner of a
-- step again in the step's run after its claim failed there (record's step_starts.go).
--
-- step_starts.owner_restarts is the count of a child's own architect's restarts in the run of a
-- step of its own, which only that architect reports: its claim failing there is started again at
-- once, since no phase start comes while the child stands at that step, but at most
-- workflow.OwnerRestarts times in one run (workflow's restartFailedOwner), so a launch that always
-- fails is not started for ever. Each start of the place begins a run with none spent
-- (record.Postgres.RaiseStepStarts, OpenUncountedStep), and the operator's retry of the owner's
-- claim gives them all back (record.Postgres.ResetOwnerRestarts). A row that has spent them all
-- leaves the claim failed, and the stranded list names it for that retry.
--
-- Every row the table already holds takes the default, 0: no restart of an owner was counted,
-- since no release before this one made one.
--
-- The release before this one names each column it reads and writes of step_starts, so it
-- neither reads nor writes this one, and every row it inserts takes the default. After a rollback
-- its starts of a place leave the count where this release left it, so at the roll-forward a run
-- it started may begin with restarts spent: the owner of that run is started again fewer times
-- before the stranded list names it.
--
-- There is no down file. This directory keeps none, so the way back is the one transaction that
-- closes this header, its last paragraph (migrations.WayBack), run with this release's daemon
-- stopped and before the release before starts, through psql '<postgres_dsn>' -X -v
-- ON_ERROR_STOP=1. The release before needs neither statement to run, since it never names the
-- column: the delete of this migration's row is what makes the version the store reports that
-- release's own again, and the drop is what lets this file run again at the roll-forward, which
-- then adds the column at its default. What the drop costs is the counts: after the roll-forward
-- the owner of a run already started again is started again as many times more.
--
-- begin;
-- alter table step_starts drop column if exists owner_restarts;
-- delete from schema_version where version = 20261125115100;
-- commit;
alter table step_starts add column owner_restarts integer not null default 0;
