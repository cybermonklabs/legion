-- 20261123165139_experiment_assignment_plan.up.sql — how the issue a draw was made for is done.
--
-- A variant of an experiment may name `plan` (config.Variant.Plan): `owner`, whose issues take the
-- plan their owner gives, or `default`, whose issues run the project's default steps and take no
-- plan from their owner. The draw records that word on its row beside the arm
-- (experiment.DrawAndRecord), so an issue keeps the way it is done for its whole life, whatever
-- the project's file says later: the row is written once and never updated
-- (20261111045636_experiment_assignments, the paragraph on the primary key). The workflow reads it
-- off the issue's own rows (experiment.GroupOf). The check keeps the empty word, the two words the
-- loader takes, and `owner-alone`, the owner doing the whole issue itself in one step: the loader
-- refuses that word in this release (config's readVariants), so no draw writes it, and the check
-- holds it so that a release that carries it out needs no migration to write it.
--
-- It back-fills nothing. Every row written before it reads '', which is an issue of no group: it
-- runs as an issue with no experiment runs, as it did when it was drawn. A carried or settled row
-- (record.Store.CarryAssignments) names its columns and leaves this one out, so it reads '' too,
-- and only a tree row is carried, which no experiment that sets plan draws (config's
-- checkExperimentPlans holds such an experiment to unit issue).
--
-- Rolling back onto a release before this migration takes `plan` out of `legion.yaml` first, with
-- the daemon stopped and before the earlier image is pinned (docs/kubernetes.md, "Rolling back the
-- release whose experiment sets how each issue is done"). That release's loader knows no `plan`
-- of a variant and refuses the file naming it (`unknown key
-- projects.<KEY>.experiments.<name>.variants.<arm>.plan`, its config's describedMembers), so its
-- daemon does not start while one arm names it: take the key out of every arm that names it, or
-- the experiment out of the file. The database needs nothing taken off. That release names the
-- columns of experiment_assignments in each statement it runs — its record.Store's
-- assignmentColumns, PutAssignments and CarryAssignments — so it boots with the column in place,
-- reads no word of it, and writes '' into it at each draw. What the roll back costs: an issue
-- drawn into `default` before the roll back has its group read by no code while that release
-- runs, so the plan its owner gives is taken and run. Rolling forward does not undo that: the
-- row still reads `default`, so a run that started on the owner's plan goes on with it (its first
-- step does not run again), while each later version and each stop_task is answered
-- PLAN_NOT_TAKEN, so its owner can neither change nor stop that plan until the issue's next run,
-- whose first step passes the plan over, or until the issue leaves the workflow, which ends the
-- run. Rolling forward again also costs the window the other way: an issue that release drew
-- while it ran reads '' afterwards and runs as with no experiment.
alter table experiment_assignments
    add column plan text not null default ''
        check (plan in ('', 'owner', 'default', 'owner-alone'));
