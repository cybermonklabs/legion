-- 20261127171352_production_check_look_id.up.sql — each look of a production check gets a secret
-- look id of its own, and a check keeps the generation it was opened in (dispatch://INFRA-3518).
--
-- production_checks.look_id is record.ProductionCheck.LookID: the id that only the look's own task
-- gives the checking role, and that the role's report of the look gives back. look_id_look and
-- look_id_opened_at are the look number and the check instance (opened_at) the id was made for
-- (LookIDLook, LookIDOpenedAt), so an id the record still holds for a look that a later look
-- replaced, or for the check that a later merge replaced, names no look
-- (ProductionCheck.CurrentLookID).
-- opened_generation is ProductionCheck.OpenedGeneration: the issue's generation when
-- workflow.openCheck opened the check, which tells a later leave of the issue whether it ran again
-- after that merge. pending_task_deliveries.look_id is supervise.Delivery.LookID: the look id that
-- a look's task gives, which fences that task on its look.
--
-- All five columns are nullable, and every row the migration finds holds null in each of them:
-- no release before this one made a look id or recorded the generation of a check. The record
-- store reads a null as the empty id, look 0, the zero time and generation 0. The next boot of
-- this release gives each open look without an id of its own an id and a new task of that look,
-- and each open check with no generation its issue's generation.
--
-- The release before this one names each column it reads and writes in production_checks (the
-- record store's productionCheckColumns and PutProductionCheck) and in pending_task_deliveries
-- (the claim store's putDelivery and claimSelect), so it neither reads nor writes these. Its
-- upsert of a new check leaves opened_generation of the check it replaces in place, so the way
-- back below clears that column, and the next boot of this release writes each open check's
-- generation again. Its write of a new delivery names no look id, so the delivery holds no look
-- id of its own: it holds null, or keeps the look id of the delivery it replaces. This release
-- keeps and sends a look's task only while the look id its delivery holds is the current look id
-- of its look (ProductionCheck.CurrentLookID), so it drops such a task unless that kept id is the
-- current one. The release before runs a start row of a look that comes due while the look's
-- issue is out of the workflow, and finishes unrun one that comes due while the issue runs again.
-- So it can run a start row of the current look that this release queued and the way back below
-- stripped of lookId: the task then gives the look id this release made for that look, the check
-- still holds that id as its current look's, and the delivery holds no id of that look. At the
-- roll forward the send would drop that task, so the look would end with no report at its bound,
-- and the check would close not_run where that look is its last; the operator claim view, which
-- withholds only the id a delivery holds, would show the current look's id. So the way back below
-- clears the look id of each open check whose issue is out of the workflow, and the roll forward's
-- boot gives each open look with no look id of its own a new look id and a new task of that look,
-- which replaces the old task: the old id is then the id of no current look. The way back keeps
-- the look id of each open check whose issue runs again, a root re-admitted after its check's
-- merge: the root's checking role can hold that id from the task of the look, and a report with
-- that id counts while the root runs (decision 7 of dispatch://INFRA-3518), so a cleared id would
-- lose that report. Such a look keeps its id through the roll forward while its issue still runs,
-- and its checking role reports with it. Where the issue left the workflow before the roll forward
-- and the checking role's claim holds a task of that look whose delivery holds no look id or
-- another one, the boot gives the look a new look id and a new task of that look as well
-- (workflow.Engine.RepairOpenChecks). So it does where a start row of that look stays queued for
-- that role through the roll forward with its look id taken off, which the fence would finish
-- unrun. Each other look id the way back leaves is a closed check's.
-- The release before's upsert of the check that a later merge opens, and its start of the next
-- look of an open check whose look id the way back kept, leave the look id as this release wrote
-- it, which CurrentLookID reads as no id of the current look, and the boot gives that look an id
-- of its own and a new task.
--
-- This release also writes the keys lookId and lookReissue into supervise rows
-- (record.SuperviseRequest.LookID and LookReissue), and queues supervise rows of the op
-- retire_look, which end a look's task when its look ends. The release before this one knows no
-- such key and no such op, and decodes an outbox payload strictly (record.DecodeOutboxPayload,
-- DisallowUnknownFields), so each such row would fail to decode there on every attempt. A start
-- stripped of the two keys runs under the release before as a start of its look. Its task, and
-- the task of a delivery a claim holds, still give the look id and ask for look_id, which the
-- earlier plugin's strict handoff_complete refuses, so the checking role sends its report again
-- without it. A retire_look row has nothing the release before can run, and is deleted. The
-- release before closes a child's check at the child's re-entry, and no leave of a run closes a
-- check under it, so the open check of a child that runs again, which this release keeps open,
-- is closed not_run, as the release before would have closed it at the re-entry.
--
-- There is no down file. This directory keeps none: migrations here are forward-only and no
-- .down.sql file exists. The release's whole way back is the section of docs/kubernetes.md
-- "Rolling back the release whose look report gives its look id", whose block is the last
-- paragraph of this header (migrations.WayBack), run with every daemon of the database stopped
-- and before the release before starts, through psql '<postgres_dsn>' -X -v ON_ERROR_STOP=1,
-- once for each project that rolls back. Daemons of several projects can share the database, and
-- each runs only its own project's rows (split_part(issue, '-', 1)), so each statement names the
-- project, <PROJECT>, which the operator replaces with its key, and leaves the rows and the
-- checks of every project that stays on this release. It drops no column and deletes no version
-- row, so the roll forward finds the five columns and applies nothing. internal/textcheck's
-- TestTheLookIDWayBackIsOneTextInTheHeaderAndTheGuide holds the guide's block and this one to one
-- text, and internal/store's
