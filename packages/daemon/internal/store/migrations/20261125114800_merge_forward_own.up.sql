-- 20261125114800_merge_forward_own.up.sql — the mark of an ask to merge forward made at the task's
-- implementation step.
--
-- pull_requests.merge_forward is record.PullRequest.MergeForward, and its key `own`
-- (record.MergeForward.Own) says the ask was made while the task stood at the step of the agent it
-- asks: implementing on today's steps, or a step of the type implementation under another role's
-- name. Such an ask covers that step alone, so once the task stands elsewhere at the same head the
-- daemon asks again, with the hold and the notice the ask at that step did not send, and the ask
-- tells its agent that its own assignment and its completion stand. The daemon now reads that from
-- the mark and no longer from the phase alone, which cannot tell the implementation step from
-- another step that runs as the same phase.
--
-- The release before asked the implementer alone, and every ask it recorded in implementing it
-- made at the implementer's own step, so this file marks each such ask. An ask it recorded in
-- another phase was made away from that step and stays unmarked, as before, and a pull request that
-- holds no ask stays null.
--
-- The release before reads the column into a struct that knows no `own` and decodes it leniently,
-- so it reads a marked ask as it wrote it, and its next write of an ask leaves the mark out. There
-- is no down file. This directory keeps none — migrations here are forward-only and no .down.sql
-- file exists — so the way back is the one transaction that closes this header, its last paragraph
-- (migrations.WayBack), run before the release before starts, through psql '<postgres_dsn>' -X -v
-- ON_ERROR_STOP=1. It deletes this migration's version row alone, which is owed to the
-- roll-forward: that runs this file again and marks each ask the release before recorded in
-- implementing in between.
--
-- begin;
-- delete from schema_version where version = 20261125114800;
-- commit;
update pull_requests set merge_forward = merge_forward || '{"own": true}'::jsonb
  where merge_forward is not null and merge_forward->>'phase' = 'implementing';
