-- 20261126070017_model_requests_retried_refusals.up.sql — whether each model request a host
-- reported came in a batch whose host reports the HTTP 429s its transport retries by itself.
--
-- The provider's refusals (signals.RefusalsAt) count every refused request of the hour before a
-- moment. The Claude Code bridge reports each 429 its transport retries as a refused request of its
-- own, and the pinned Oh My Pi host gives an extension no event for such an attempt, so that host's
-- refusals are known to count short. Each batch says which its host is
-- (claim.ModelRequestsRequest's retriedRefusalsReported), and admission keeps each request with it
-- (record.Store.KeepModelRequests):
--
--   - model_requests.retried_refusals_reported is true where the request's batch said its host
--     reports those 429s, and false where it said it does not or said nothing, as a host of a
--     contract before the member does. While a request kept false ended in the hour the refusals
--     read, or in the minute under way, they are not recorded (record.Postgres's ProviderMinutes,
--     admit's LiveSignals); the headroom reads every request alike.
--
-- A row kept before this migration came of a batch that said nothing, so it reads false, which
-- the column's default gives it. The daemon writes the column on every row it keeps.
--
-- The migration adds a column to a table no earlier release reads, so a daemon of the release
-- before runs over the migrated database, as a rollback leaves it.
--
-- There is no down file. This directory keeps none — migrations here are forward-only and no
-- .down.sql file exists — so the way back is the one transaction that closes this header, its last
-- paragraph (migrations.WayBack), run with every daemon that shares the database stopped and before
-- the release before starts, through psql '<postgres_dsn>' -X -v ON_ERROR_STOP=1, before the way
-- back of 20261126042544_model_requests. Dropping the column and deleting this version row lets the
-- roll-forward apply this migration anew, every row then read as of a host that said nothing.
--
-- begin;
-- alter table model_requests drop column if exists retried_refusals_reported;
-- delete from schema_version where version = 20261126070017;
-- commit;
alter table model_requests add column retried_refusals_reported boolean not null default false;
