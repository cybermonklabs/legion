-- 20261109144422_claim_retired_at_row.up.sql — where the outbox stood when a claim retired, so
-- that the repair of a start that can no longer act can order an owed start row against the stop
-- of its worker rather than guess at it (INFRA-1573).
--
-- claims.retired_at_row is the outbox's high-water row id at the moment a claim's retirement was
-- recorded: the write that moves the claim into retired takes it, in the same statement
-- (store's putClaim), and every other write leaves the column where it stands. A row of the
-- outbox at or below that mark stood there when the worker was stopped, and a row above it was
-- written after the stop — which is the whole of what admit's stopOutlivedStart needs to tell a
-- start the stop outlived from the workflow's own next start of that worker.
--
-- The mark is `select coalesce(max(id), 0) from outbox` over the live table, not the sequence's
-- own last_value. Outbox ids come from one increasing sequence, so a row that exists when the
-- mark is taken has an id at or below it and every row written after it has one above it. A row
-- another transaction has inserted and not committed is invisible to that read, so the mark can
-- only come out lower than the truth, which keeps an owed row rather than ending one: the safe
-- direction, since ending a row the workflow still means to run would strand the issue with
-- nothing to start its phase. The sequence's last_value counts every id handed out, committed or
-- not, and so errs the other way.
--
-- Zero for every row the table already holds, and nothing backfills it: the release this upgrades
-- from recorded the moment of a retirement nowhere, and there is nothing to read a backfill from.
-- A claim an earlier release retired therefore carries 0, which is below every outbox id (the
-- sequence starts at 1), so no owed start row of such a claim is ever ended and it behaves
-- exactly as it does today — the operator's stop of such a worker holds as it held before this
-- column, and the repair of a slot and the rest of the pass are untouched.
--
-- A claim that comes back to life — a retry, a re-admission — keeps the mark its last retirement
-- took until it retires again, and no reader looks at it: the rule reads the mark only for a
-- claim that is in retired now.
--
-- Rolling the image back needs no restore of the database: store's claims.go is the only writer
-- and record's readRoleClaims the only reader, and the release before this one names the column
-- in no statement, so an upsert of that release leaves whatever the column last held. That
-- release reads a stop the way it always did, and a daemon of this release rolled forward again
-- reads the mark back — stale by whatever that release's own retirements wrote, which can only
-- leave the mark lower than the truth, the safe direction above.
alter table claims add column retired_at_row bigint not null default 0;
