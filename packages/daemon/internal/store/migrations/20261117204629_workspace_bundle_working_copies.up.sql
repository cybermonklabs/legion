-- 20261117204629_workspace_bundle_working_copies.up.sql — a saved workspace bundle names the
-- working copy of each task of the issue beside the issue's own.
--
-- working_copies maps the branch of each task whose working copy sat beside the issue's, in the
-- released pod's clone, to the commit that working copy sat on: `{"legion/<KEY>.<part>":
-- "<commit>"}` (runtime.WorkspaceBundle.WorkingCopies). The release's save writes it with the rest
-- of the bundle (store.PutWorkspaceBundle), the take of the pod that replaces the released one
-- reads it back (store.TakeWorkspaceBundleForRestore), and that pod's launcher puts a workspace
-- back on each commit before any role starts (internal/launcher's restoreTaskCopies). Without the
-- column the store drops the map, and the replacement pod gets the issue's working copy alone.
--
-- Every row the table already holds takes the default, the empty object: a shim of the release
-- before this one saved no working copy of a task, so the restore of such a row puts back the
-- issue's working copy alone, as that release's restore did.
--
-- The release before this one boots with the column in place and reads none of it. Its take
-- returns the columns its statement names (`at, head, tips, bookmarks, release_id,
-- source_pod_uid`, internal/store/workspace_bundles.go:113-119 of that release), so a row this
-- release saved with working copies restores the issue's working copy alone there; the commits of
-- each task's working copy are heads the bundle carries (the shim's bundleKeptRevset), so they are
-- visible in the restored clone with no workspace on them. Its save's upsert (:43-48 of that
-- release) names no working_copies either, so a row it saves over one this release saved would
-- keep the older map beside its own bundle: the way back below drops the column, which ends that
-- along with the rest.
--
-- There is no down file. This directory keeps none — migrations here are forward-only and no
-- .down.sql file exists — so the way back is the transaction below, run with the daemon stopped:
--
--   psql '<postgres_dsn>' -X -v ON_ERROR_STOP=1 <<'SQL'
--   begin;
--   alter table workspace_bundles drop column if exists working_copies;
--   delete from schema_version where version = 20261117204629;
--   commit;
--   SQL
--
-- The drop is owed to the roll-forward, not to the release before: with the column dropped and
-- the row deleted, store.apply finds no row of this version and runs this file again, which adds
-- the column again at its default, and an add of a column that stands would fail. What the drop
-- costs is the map of a bundle saved and not yet restored, whose restore then puts back the
-- issue's working copy alone.
alter table workspace_bundles add column working_copies jsonb not null default '{}';
