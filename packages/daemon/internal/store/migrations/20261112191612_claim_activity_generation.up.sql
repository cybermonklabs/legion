-- 20261112191612_claim_activity_generation.up.sql — which launch of the claim wrote the activity
-- report the four activity columns hold, so a report a process that is gone left behind is read
-- as no report at all.
--
-- The four columns (activity_at, activity_background, activity_kinds, activity_next_reminder_at)
-- survive a relaunch: only the activity route writes them (store's PutClaimActivity), and a
-- claim's own write neither carries them nor erases them. So a worker displaced into a
-- replacement pod while a background task of its own was running leaves a report behind that
-- describes work its replacement killed, and the rules that read that report — the idle
-- release's hold on a pod whose session says work of its own is running or whose phase reminder
-- is armed, and the silence repair's exclusion of such a worker — act on a process that no
-- longer exists. An Oh My Pi session replaces the stale report within five seconds, but a Claude
-- Code session reports at its Stop hook alone (packages/claude-envoy/src/legion-phase-hook.ts),
-- and a worker nothing will prompt reaches no Stop, so nothing repairs its report at all.
--
-- activity_generation is the claim's generation as it stood when the report was written, stamped
-- by the same update that writes the four (claims.generation, which every launch increments and
-- persists: supervise's launchNow). Every reader of those columns drops the report whose stamp is
-- set and is not the row's own generation, leaving the zero values that already mean this
-- session has reported nothing.
--
-- Null is a report written before this release, and it is read as the current process's: every
-- live process on the day of the deploy reported under a generation nothing recorded, so the only
-- honest reading of such a report is the one the daemon gave it before the column existed. No
-- backfill, for that same reason, and none is needed: every live session stamps its next report.
alter table claims add column activity_generation bigint;
