import { z } from "zod";
import {
  DispatchEventSchema,
  DispatchTargetedCommentDeliverySchema,
  DispatchTargetedCommentPayloadSchema,
  DispatchTargetedMessageDeliverySchema,
  DispatchTargetedMessagePayloadSchema,
  readDispatchPayload,
} from "../src/dispatch-api";
import { dispatchFrameCorpus } from "./dispatch-frame-corpus";

// gen-go's Dispatch frame outputs: the shapes a host reads a Dispatch envelope's payload by
// (readDispatchPayload, which the plugin's renderInbound calls), rendered as JSON Schema from the
// zod schemas themselves - the event's header and, for a targeted frame, the two delivery lines and
// the two payloads a frame of each kind carries - and the verdict readDispatchPayload gives each
// payload of dispatchFrameCorpus. The choice among the shapes - a message.created event with a
// message's delivery line and a message's payload, or a comment.created event with a comment's - is
// DispatchTargetedFrameSchema's refinement, which JSON Schema cannot say; the edge listener's Go
// reader makes it by hand (DispatchPayloadIsEvent), and the verdict fixture holds the two together.

function dispatchShape(schema: z.ZodType) {
  const { $schema: _, ...shape } = z.toJSONSchema(schema, {
    io: "input",
    unrepresentable: "throw",
    reused: "inline",
  }) as Record<string, unknown>;
  return shape;
}

/** The JSON Schema of the shapes, as schemas/dispatch-frame.schema.json holds it. */
export function renderDispatchFrameSchema() {
  return `${JSON.stringify(
    {
      $schema: "https://json-schema.org/draft/2020-12/schema",
      $comment:
        "Generated by scripts/gen-go.ts (gen-go-dispatch-frame.ts) from DispatchEventSchema and the targeted schemas of src/dispatch-api-events.ts and src/dispatch-api-targeted.ts. DO NOT EDIT.",
      $defs: {
        event: dispatchShape(DispatchEventSchema),
        messageDelivery: dispatchShape(DispatchTargetedMessageDeliverySchema),
        commentDelivery: dispatchShape(DispatchTargetedCommentDeliverySchema),
        messagePayload: dispatchShape(DispatchTargetedMessagePayloadSchema),
        commentPayload: dispatchShape(DispatchTargetedCommentPayloadSchema),
      },
    },
    null,
    2
  )}\n`;
}

/** fixtures/dispatch-frame-verdicts.json: readDispatchPayload's kind for each corpus payload. */
export function renderDispatchFrameVerdicts() {
  return `${JSON.stringify(
    dispatchFrameCorpus().map(({ name, payload }) => {
      let value: unknown;
      try {
        value = JSON.parse(payload);
      } catch {
        return { name, payload, kind: "raw" };
      }
      return { name, payload, kind: readDispatchPayload(value).kind };
    }),
    null,
    1
  )}\n`;
}

/** The Go file that carries the schema for DispatchPayloadIsEvent, rendered from the same string
 *  as schemas/dispatch-frame.schema.json. */
export function renderDispatchFrameSchemaGo(schema: string) {
  if (schema.includes("`")) {
    throw new Error("the Dispatch frame schema holds a backtick, which a Go raw string cannot");
  }
  return `// Code generated by packages/contracts/scripts/gen-go.ts (gen-go-dispatch-frame.ts) from the zod
// schemas readDispatchPayload reads a Dispatch payload by, as schemas/dispatch-frame.schema.json
// is. DO NOT EDIT.

package contracts

// dispatchFrameSchemaJSON is the JSON Schema of the shapes a host reads a Dispatch envelope's
// payload by (readDispatchPayload in packages/contracts), which DispatchPayloadIsEvent checks.
const dispatchFrameSchemaJSON = \`${schema.trimEnd()}\`
`;
}
