import { describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";

const generator = resolve(import.meta.dir, "gen-api.ts");
const repoRoot = resolve(import.meta.dir, "../../..");

// The module each document renders into, with a line each must hold: the header naming the
// document it came from, and one alias of a schema only that document declares.
const MODULES = [
  {
    document: "schemas/dispatch-openapi.json",
    output: resolve(import.meta.dir, "../src/dispatch-api.generated.ts"),
    alias: 'export type Issue = components["schemas"]["Issue"];',
  },
  {
    document: "schemas/dispatch-openapi-v2.json",
    output: resolve(import.meta.dir, "../src/dispatch-api-v2.generated.ts"),
    alias: 'export type AskV2 = components["schemas"]["AskV2"];',
  },
];

describe("gen-api", () => {
  // The generator shells out to Biome, so Bun's 5 s default cannot cover a cold CI runner.
  test("the committed client types of both documents are what the generator emits", async () => {
    const process = Bun.spawn(["bun", generator, "--check"], {
      cwd: repoRoot,
      stderr: "pipe",
      stdout: "pipe",
    });
    const stderr = await new Response(process.stderr).text();
    const exitCode = await process.exited;

    expect(stderr).toBe("");
    expect(exitCode).toBe(0);

    for (const module of MODULES) {
      const source = await Bun.file(module.output).text();
      expect(source).toContain(
        `// Code generated by scripts/gen-api.ts from ${module.document}. DO NOT EDIT.`
      );
      expect(source).toContain(module.alias);
    }
  }, 120_000);

  // A hand-edit of a generated file fails CI naming the file it found stale. The hand-edit lands
  // on a copy under GEN_API_CHECK_ROOT, never on the tracked file this workspace shares; the
  // other module's copy is the committed file as it stands, so only the edited one is stale.
  for (const edited of MODULES) {
    test(`a hand-edit of ${relative(repoRoot, edited.output)} makes --check fail, naming it`, async () => {
      const root = mkdtempSync(join(tmpdir(), "gen-api-check-"));
      try {
        for (const module of MODULES) {
          const copy = resolve(root, relative(repoRoot, module.output));
          mkdirSync(dirname(copy), { recursive: true });
          const committed = await Bun.file(module.output).text();
          await Bun.write(copy, module === edited ? `${committed}// hand-edited\n` : committed);
        }
        const staleCopy = resolve(root, relative(repoRoot, edited.output));

        const spawned = Bun.spawn(["bun", generator, "--check"], {
          cwd: repoRoot,
          env: { ...process.env, GEN_API_CHECK_ROOT: root },
          stderr: "pipe",
          stdout: "pipe",
        });
        const stderr = await new Response(spawned.stderr).text();
        const exitCode = await spawned.exited;

        expect(exitCode).not.toBe(0);
        expect(stderr).toContain(`${staleCopy} is stale`);
        for (const module of MODULES.filter((module) => module !== edited)) {
          expect(stderr).not.toContain(
            `${resolve(root, relative(repoRoot, module.output))} is stale`
          );
        }
      } finally {
        rmSync(root, { force: true, recursive: true });
      }
    }, 120_000);
  }
});
