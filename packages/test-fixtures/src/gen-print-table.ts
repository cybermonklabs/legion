// Writes print-table.ts, the print test's TWIN_PLACEMENTS, by measurement: for each holder kind,
// printer and placement, it prints the kind's representative twins (KINDS) and records the first
// placement of the first twin at which the printer prints a marker. It tries the row's own
// placement first, then a public property, then the value itself, and at each the twin of the
// row's own shape first, then the exported twin, then the probe as a string. A row no twin reaches
// is recorded "unreachable", which the print test reads as blind. Go's half is
// packages/envoy/internal/redact/redacttest/gentable.
//
// Run it from packages/test-fixtures: bun run src/gen-print-table.ts.
import { writeFileSync } from "node:fs";
import { KINDS, PLACEMENTS, PRINTERS, secretsIn, twinOf } from "./print-test";

function measure(kind: string, printer: string, at: string): string {
  const { same } = (KINDS[kind] as () => { same: unknown })();
  const holder = { name: kind, kind, boxed: undefined, same };
  const print = PRINTERS[printer] as (v: unknown) => string;
  for (const where of [...new Set([at, "property", "value"])]) {
    for (const variant of ["same", "exported", "string"]) {
      const record = variant === "same" && where === at ? "same" : `${variant}@${where}`;
      const [twin] = twinOf(holder, at, record);
      if (twin !== undefined && secretsIn(print(twin)).length > 0) return record;
    }
  }
  return "unreachable";
}

const lines = [
  "// Generated by gen-print-table.ts; do not edit.",
  "//",
  '// The twin placement of every holder kind, printer and placement ("<kind>|<printer>|<placement>"):',
  '// "same", the row\'s own placement and twin; "<variant>@<placement>", the exported twin, whose',
  "// fields are public properties, or the probe as a string, where the printer cannot read a `#`",
  "// field, or another placement, where it cannot reach a plain string at the row's own; or",
  '// "unreachable". Measured on each kind\'s representative twins (KINDS); the print test reads it',
  "// as it is and repairs nothing.",
  "export const TWIN_PLACEMENTS: Record<string, string> = {",
];
for (const kind of Object.keys(KINDS).sort()) {
  for (const printer of Object.keys(PRINTERS)) {
    for (const at of Object.keys(PLACEMENTS)) {
      lines.push(
        `  ${JSON.stringify(`${kind}|${printer}|${at}`)}: ${JSON.stringify(measure(kind, printer, at))},`
      );
    }
  }
}
lines.push("};", "");
writeFileSync(new URL("./print-table.ts", import.meta.url), lines.join("\n"));
