-- A secret behind Cipher's proxy is behind a kind of the profiles file: the kind's hosts are where
-- its credential may go, and its headers are where the credential travels. A kind that loses a
-- host or a header must end the grants decided under it, and one that only gains one must end
-- none. No fingerprint of the file alone tells a loss from a gain, so each name a request names
-- records the hosts and headers of its kind as the request was decided, and again as it was
-- approved: a release ends the grant once a recorded host or header is missing from the kind the
-- policy holds then (requests.kindLost).
--
-- airlock_kind is {"hosts": [...], "headers": [...]}, each as the profiles file writes it, the
-- headers with the default Authorization where the kind names none. It is null for a name behind
-- no kind, a dpop block's included, whose minted grants their entry digest covers, and for every
-- row written before this migration. The column is nullable and has no default, so adding it
-- rewrites no row and the release before this one, which writes none, still inserts as it did.
alter table request_secrets add column airlock_kind jsonb null;
