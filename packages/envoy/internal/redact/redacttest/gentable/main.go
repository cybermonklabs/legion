// Command gentable writes redacttest's TwinPlacements (printtable.go) by measurement: for each
// holder kind, printer and placement, it prints the kind's representative twins (redacttest.Kinds)
// and records the first placement of the first twin at which the printer prints a marker. It
// tries the row's own placement first, then an exported field, then the value itself, and at each
// the twin of the row's own shape first, then the exported twin, an error and a Stringer. A row no
// twin reaches is recorded "unreachable", which the print test reads as blind.
//
// Run it from packages/envoy: go run ./internal/redact/redacttest/gentable.
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/sjawhar/envoy/internal/redact/redacttest"
)

const out = "internal/redact/redacttest/printtable.go"

func main() {
	kinds := make([]string, 0, len(redacttest.Kinds))
	for kind := range redacttest.Kinds {
		kinds = append(kinds, kind)
	}
	sort.Strings(kinds)
	var b strings.Builder
	b.WriteString(`// Code generated by redacttest/gentable; DO NOT EDIT.

package redacttest

// TwinPlacements records, for each holder kind, printer and placement
// ("<kind>|<printer>|<placement>"), where the print test places the plain-string twin: "same",
// the row's own placement and twin; "<variant>@<placement>", another twin (exported, an error, a
// Stringer) or another placement, where the printer cannot reach a plain string at the row's own;
// or "unreachable". gentable measured it on each kind's representative twins (Kinds). The print
// test reads it as it is and repairs nothing: a recorded placement the printer cannot reach makes
// the row blind.
var TwinPlacements = map[string]string{
`)
	for _, kind := range kinds {
		same, exported := redacttest.Kinds[kind]()
		h := redacttest.Holder{Name: kind, Kind: kind, Same: same, Exported: exported}
		for _, printer := range redacttest.Printers {
			for _, at := range redacttest.Placements {
				fmt.Fprintf(&b, "\t%q: %q,\n", kind+"|"+printer.Name+"|"+at.Name, measure(h, printer, at.Name))
			}
		}
	}
	b.WriteString("}\n")
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gentable:", err)
		os.Exit(1)
	}
}

// measure answers the record of the first twin and placement at which printer prints a marker.
func measure(h redacttest.Holder, printer redacttest.Printer, at string) string {
	for _, where := range dedupe(at, "exported", "value") {
		for _, variant := range []string{"same", "exported", "error", "stringer"} {
			record := variant + "@" + where
			if variant == "same" && where == at {
				record = "same"
			}
			twin, _ := h.Twin(at, record)
			if twin == nil {
				continue
			}
			if text, ok := printer.Print(twin); ok && len(redacttest.Leaks(text)) > 0 {
				return record
			}
		}
	}
	return "unreachable"
}

func dedupe(names ...string) []string {
	var out []string
	for _, n := range names {
		if !contains(out, n) {
			out = append(out, n)
		}
	}
	return out
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}
