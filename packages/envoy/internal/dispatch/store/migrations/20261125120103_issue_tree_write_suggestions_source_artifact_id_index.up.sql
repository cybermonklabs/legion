-- pgmigrate:non-transactional
-- 20261125120103_issue_tree_write_suggestions_source_artifact_id_index.up.sql - the suggestions
-- offered on a project document's ask, by that document.
--
-- The removal of a document deletes its artifacts row (api's removeArtifact), and Postgres checks
-- every foreign key to artifacts (id) for that row. write_suggestions_source_artifact_id_fkey
-- cascades, so its check deletes the suggestions whose source_artifact_id names the row. No index
-- of write_suggestions led by source_artifact_id held every suggestion:
-- write_suggestions_pending_artifact leads with it but holds only the suggestions whose outcome is
-- still 'ignored', so the delete read every row of write_suggestions, while the removal holds the
-- issue's owner lock that every comment, ask and upload of the issue waits on. This index holds
-- every suggestion, keyed by source_artifact_id alone, so the delete is one probe of it (this
-- issue's spec R7).
--
-- write_suggestions grows with the suggestions offered on every issue and ask filed. A concurrent
-- build does not hold off its writers while it scans the table, so the migration runs outside a
-- transaction, alone in its file, as the census admits a concurrent build of any table's size
-- (pgmigrate's ConcurrentIndex, this issue's spec R19). It is a performance index: no constraint
-- and no later migration depends on it, and the release before reads and writes write_suggestions
-- as it did. A failed concurrent build leaves an INVALID index of this name on write_suggestions,
-- which the runner drops with DROP INDEX CONCURRENTLY and builds again on the next attempt.
create index concurrently if not exists write_suggestions_source_artifact_id
    on write_suggestions (source_artifact_id);
