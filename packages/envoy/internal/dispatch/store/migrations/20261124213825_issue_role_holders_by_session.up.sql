-- 20261124213825_issue_role_holders_by_session.up.sql — each session that holds a role of an issue,
-- two sessions of one role among them, with the claim it holds the role by.
--
-- 20261116163813 keyed issue_role_holders by (issue_key, role), as the daemon then kept one claim
-- per issue and role. Two claims of one issue can now hold one role: the agent of a key works a
-- step of another role than its name, beside that role's own claim of an earlier version of the
-- plan. The daemon publishes the session of each live claim
-- (PUT /api/v1/issues/{key}/role-holders, api/issue_role_holders.go), so the set of such an issue
-- named a role twice, the route refused it whole (400 INVALID_ROLE_HOLDER), the daemon ended the
-- publication, and the second claim's session held no role on Dispatch.
--
-- The key is now the unique index on (issue_key, session) 20261116163813 made, which keeps each
-- session to one role of an issue: the primary key on (issue_key, role) is dropped, so a role can
-- have several sessions. claim is the token of the claim the session holds its role by, and
-- works_step whether that claim works the role's step as the daemon's record gives it; a row the
-- release before wrote names neither, the empty string and false.
--
-- The release before cannot write the rekeyed table. Its PUT inserts with `on conflict (issue_key,
-- role)`, which Postgres refuses (42P10) where no unique index on exactly those columns stands, so
-- while both releases serve, the release before answers a publication 500. The Legion daemon is
-- the table's one writer, and its outbox retries a 500 on that row rather than ending it
-- (packages/daemon's permanentRefusal), so the publication lands once a server of this release
-- takes it, and nothing is lost. The release before's reads, of an issue's set and of the role of
-- one session, answer over the rekeyed table as they did. This migration is therefore the one
-- exception to the two-build rule of internal/dispatch/store/README.md, which says so.
--
-- Each statement is one of the census's catalog-only forms (pgmigrate's catalogOnlyAlterTable: a
-- dropped constraint without cascade, which drops the primary key's index with it, and an added
-- column whose constant default Postgres stores in the catalog), so it is exempt from the table
-- size limit at any size, and holds ACCESS EXCLUSIVE on issue_role_holders for its catalogue write
-- alone, under the runner's lock_timeout. No row is refused or rewritten, so the census answers 0.
--
-- There is no down file. The way back is the one transaction that closes this header, run against
-- Dispatch's database with this release's servers stopped and before the release before starts,
-- through psql '<DATABASE_URL>' -X -v ON_ERROR_STOP=1, and before the way back of any earlier
-- migration. It folds each role two sessions hold back to one row, the session whose claim works
-- the role's step, else the newest (recorded_at, then session), since the release before keeps
-- one session per role; drops claim and works_step; puts the primary key on (issue_key, role)
-- back; and deletes this migration's version row, so that the roll forward runs this file again.
-- What the way back costs is the session of each other claim of a role, which holds no role on
-- Dispatch until the daemon publishes the set again.
--
