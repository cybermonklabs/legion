-- pgmigrate:non-transactional
-- GET /api/v1/agents/{session_id}/answers (sessionanswers.List) finds the events a person wrote to
-- one session within its window through this index on a database of production's size and shape.
-- The index holds a person's events of the five types the read names, the predicate of
-- events_person_words_with_declines (20261111002444), by (published_destinations, created_at). So
-- one index condition holds both the session's topic (published_destinations @> array[...]) and
-- the window's start (created_at >= ...), and through this index the read reads no event that
-- only other sessions' topics received and no event older than its window. Where the window holds
-- far fewer of a person's events, the planner can read them all through
-- events_person_words_with_declines, by time alone, and keep the session's, because that read
-- costs fewer buffers there; it too reads no event older than the window.
-- events_person_words_with_declines stays for that read, and because a pod of the release before
-- this one tests the topic with = any, which GIN does not serve, and reads through that index while
-- this release rolls out.
--
-- GIN has no operator class of its own for timestamptz. The operator class of created_at here is
-- btree_gin's, which 20261125125703 creates, and a deploy before the one that applies this
-- migration must apply 20261125125703. A pending migration that creates an extension takes the
-- census's concurrent index exemption from every pending migration after it
-- (pgmigrate/exempt.go, takesLaterExemptions), and the census then refuses this build while events
-- is above its table limit (cmd/dispatch/README.md, "Pre-deploy census").
--
-- 0145 did not put a GIN index on published_destinations, because the outbox writes that array of
-- every event it publishes, and each of those writes would then write the index too: a cost of
-- every outbox write, for a read that only this route makes. That does not hold for this index,
-- because it is partial. A row takes entries only when it is a person's event of the five types,
-- at its insert and when the outbox writes its array. The outbox's writes of every other event,
-- the agents' and the system's among them, write nothing here.
--
-- fastupdate is off. With the pending list on, GIN keeps new entries in a list beside the index
-- until a vacuum or the list's size limit moves them into it, and every search reads the whole
-- list as well as the index. The read runs 28 to 29 times a second, and the inserts that match the
-- predicate are few, so each of them writes its entries into the index at once and no read pays
-- for a list.
--
-- It is built `concurrently`, outside the runner's transaction, for the reason 20261111002444's
-- header gives: events is the largest table a Dispatch deployment holds, a plain build holds SHARE
-- on it, which blocks every write to it, for as long as the build reads the table, and a
-- concurrent build takes no lock that blocks a write. A failed concurrent build leaves an INVALID
-- index of this name on events, which the runner drops with DROP INDEX CONCURRENTLY and builds
-- again on the next attempt.
create index concurrently if not exists events_person_words_destinations on events using gin (published_destinations, created_at) with (fastupdate = off) where actor->>'kind' = 'user' and type in ('ask.answered', 'comment.created', 'message.created', 'message.answered', 'ask.resolved');
