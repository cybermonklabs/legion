-- pgmigrate:non-transactional
-- 20261125120102_issue_tree_user_document_reads_artifact_id_index.up.sql - the read marks of a
-- document, by that document.
--
-- The removal of a document deletes its artifacts row (api's removeArtifact), and Postgres checks
-- every foreign key to artifacts (id) for that row. user_document_reads_artifact_id_fkey cascades,
-- so its check deletes the read marks whose artifact_id names the row. user_document_reads_pkey
-- holds artifact_id only as its second column, after login, and serves that delete only by a read
-- of the whole index, so the delete read every row of user_document_reads, while the removal holds
-- the issue's owner lock that every comment, ask and upload of the issue waits on. This index is
-- keyed by artifact_id alone, so the delete is one probe of it (this issue's spec R7).
--
-- user_document_reads holds one row for each person and each document they have read. A
-- concurrent build does not hold off its writers while it scans the table, so the migration runs
-- outside a transaction, alone in its file, as the census admits a concurrent build of any table's
-- size (pgmigrate's ConcurrentIndex, this issue's spec R19). It is a performance index: no
-- constraint and no later migration depends on it, and the release before reads and writes
-- user_document_reads as it did. A failed concurrent build leaves an INVALID index of this name on
-- user_document_reads, which the runner drops with DROP INDEX CONCURRENTLY and builds again on the
-- next attempt.
create index concurrently if not exists user_document_reads_artifact_id
    on user_document_reads (artifact_id);
